#!/usr/bin/env node
/**
 * prd:defer-oldest — cap-relief for the _STATUS.md deferral tables (PRD-312 FR-4).
 *
 * The tables sit at a 15-row cap; the "convert oldest to a PRD" rule was manual
 * prose. This command picks the earliest-Vade row (tie-break lowest PRD number)
 * and, with `--apply`, scaffolds a NEW Draft `_prds/wip/` follow-up PRD from the
 * row (numbered next-free) and removes the _STATUS row ONLY after the replacement
 * exists. It does NOT call `prd:defer` — every current deferral row points at an
 * already-SHIPPED PRD (artifacts in completed/), so prd:defer would no-op.
 * Authoring stays human-gated: this scaffolds a stub, never approves a PRD.
 *
 *   pnpm prd:defer-oldest             # default: name the candidate (no writes)
 *   pnpm prd:defer-oldest --dry-run   # same — explicit
 *   pnpm prd:defer-oldest --apply     # scaffold stub + remove the row
 */
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { REPO_ROOT, fail, ok, readCurrentState, readText } from "./prd-state-utils.mjs";
import { STATUS_PATH, parseDeferrals, reliefCandidate } from "./verify-deferred.mjs";

function slugify(label) {
  return label
    .toLowerCase()
    .replace(/`/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48) || "deferral-followup";
}

function nextFreeNumber() {
  const state = readCurrentState();
  const max = Math.max(0, ...(state?.records ?? []).map((record) => record.number));
  return max + 1;
}

// PRD-418: derive the stub author from the git identity instead of a hardcoded
// personal name; "operator" is the neutral fallback (empty config, CI, etc.).
function stubAuthor() {
  try {
    const name = execFileSync("git", ["config", "user.name"], { cwd: REPO_ROOT, encoding: "utf8" }).trim();
    return name.length > 0 ? name : "operator";
  } catch {
    return "operator";
  }
}

function removeRow(content, candidate) {
  const target = candidate.label.replace(/\s+/g, " ").trim();
  const lines = content.split("\n");
  const kept = lines.filter((line) => {
    if (!line.trim().startsWith("|")) return true;
    const cells = line.split("|").map((cell) => cell.trim());
    const matchesLabel = cells[1] === target;
    const matchesPrd = candidate.prd ? cells.some((cell) => cell === candidate.prd) : true;
    return !(matchesLabel && matchesPrd);
  });
  return kept.join("\n");
}

function main() {
  const args = process.argv.slice(2);
  const apply = args.includes("--apply");
  const content = readText(STATUS_PATH);
  const { rows } = parseDeferrals(content);
  const candidate = reliefCandidate(rows);
  if (!candidate) {
    ok("[prd:defer-oldest] no dated deferral rows — nothing to relieve");
    return;
  }

  const number = nextFreeNumber();
  const padded = String(number).padStart(3, "0");
  const slug = slugify(candidate.label);
  const newPrdPath = `_prds/wip/prd-${padded}-${slug}.md`;

  process.stdout.write(
    `[prd:defer-oldest] relief candidate:\n` +
      `  section : ${candidate.section}\n` +
      `  konu    : ${candidate.label}\n` +
      `  prd     : ${candidate.prd ?? "(none)"}\n` +
      `  vade    : ${candidate.due}\n` +
      `  not     : ${candidate.note ?? ""}\n` +
      `  → scaffold ${newPrdPath} (PRD-${padded}) and remove the row\n`,
  );

  if (!apply) {
    ok("[prd:defer-oldest] dry-run — no writes. Re-run with --apply to scaffold + remove the row.");
    return;
  }

  const abs = resolve(REPO_ROOT, newPrdPath);
  if (existsSync(abs)) fail(`[prd:defer-oldest] ${newPrdPath} already exists — pick the number manually`);

  const today = new Date().toISOString().slice(0, 10);
  const author = stubAuthor();
  const stub = [
    `# PRD-${padded}: ${candidate.label}`,
    "",
    "> **Status**: Draft",
    "> ",
    `> **Created**: ${today}`,
    `> **Updated**: ${today}`,
    `> **Author**: ${author}`,
    "> **Audience**: Implementing Agent (Claude Code / Cursor / Codex)",
    `> **Slug**: \`${slug}\``,
    "> **Cycle Phase**: 1 (PRD Generation)",
    "> **PRD Class**: infra",
    "> **Class Rationale**: Converted from a _STATUS.md deferral row by prd:defer-oldest; classify properly during Phase 1.",
    "> **Autonomous Close**: operator-gated",
    "> **State Record**: `_state/prds.json` (generated by `pnpm state:sync`)",
    "",
    "---",
    "",
    "## 1. Introduction / Overview",
    "",
    `Converted from the deferral row **${candidate.label}** (was ${candidate.prd ?? "n/a"}, vade ${candidate.due}).`,
    "",
    `> ⚠ SCAFFOLD STUB — needs a real Phase-1 author pass before Phase 2. Source note:`,
    `> ${candidate.note ?? "(none)"}`,
    "",
  ].join("\n");
  writeFileSync(abs, `${stub}\n`);

  const after = removeRow(content, candidate);
  writeFileSync(STATUS_PATH, after);

  for (const cmd of [["verify:deferred"], ["state:sync"], ["state:status-panel"]]) {
    try {
      execFileSync("pnpm", cmd, { cwd: REPO_ROOT, stdio: "inherit" });
    } catch {
      /* surfaced to the operator; non-fatal here */
    }
  }
  ok(`[prd:defer-oldest] scaffolded ${newPrdPath} and removed the row — author it in Phase 1 before Phase 2.`);
}

if (process.argv[1]?.endsWith("prd-defer-oldest.mjs")) main();
